CREATE TABLE products (
    id          VARCHAR(40)  PRIMARY KEY,
    sku         VARCHAR(16)  NOT NULL UNIQUE,
    name        VARCHAR(120) NOT NULL,
    category    VARCHAR(20)  NOT NULL,
    unit_price  NUMERIC(12, 2) NOT NULL CHECK (unit_price > 0),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT products_category_chk CHECK (category IN ('ELECTRONICS', 'GROCERY', 'APPAREL', 'HOME', 'TOYS'))
);

CREATE TABLE customers (
    id          VARCHAR(40)  PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    email       VARCHAR(254) NOT NULL UNIQUE,
    tier        VARCHAR(20)  NOT NULL,
    region      VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT customers_tier_chk CHECK (tier IN ('STANDARD', 'SILVER', 'GOLD', 'PLATINUM')),
    CONSTRAINT customers_region_chk CHECK (region IN ('NORTH', 'SOUTH', 'EAST', 'WEST'))
);

CREATE TABLE stock_items (
    sku       VARCHAR(16) PRIMARY KEY REFERENCES products (sku),
    on_hand   INTEGER NOT NULL CHECK (on_hand >= 0),
    reserved  INTEGER NOT NULL DEFAULT 0 CHECK (reserved >= 0),
    CONSTRAINT stock_reserved_le_on_hand CHECK (reserved <= on_hand)
);

CREATE TABLE coupons (
    code          VARCHAR(32) PRIMARY KEY,
    type          VARCHAR(20) NOT NULL,
    amount        NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (amount >= 0),
    min_spend     NUMERIC(12, 2),
    max_discount  NUMERIC(12, 2),
    valid_from    DATE,
    expires_on    DATE,
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT coupons_type_chk CHECK (type IN ('PERCENTAGE', 'FIXED_AMOUNT', 'FREE_SHIPPING')),
    CONSTRAINT coupons_window_chk CHECK (valid_from IS NULL OR expires_on IS NULL OR valid_from <= expires_on)
);

CREATE TABLE orders (
    id              VARCHAR(40) PRIMARY KEY,
    customer_id     VARCHAR(40) NOT NULL REFERENCES customers (id),
    status          VARCHAR(20) NOT NULL,
    coupon_code     VARCHAR(32) REFERENCES coupons (code),
    subtotal        NUMERIC(12, 2) NOT NULL,
    discount_total  NUMERIC(12, 2) NOT NULL,
    tax_total       NUMERIC(12, 2) NOT NULL,
    shipping_total  NUMERIC(12, 2) NOT NULL,
    total           NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    version         BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT orders_status_chk CHECK (status IN ('CREATED', 'PAID', 'SHIPPED', 'DELIVERED', 'CANCELLED'))
);

CREATE TABLE order_lines (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    VARCHAR(40) NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    line_no     INTEGER NOT NULL,
    sku         VARCHAR(16) NOT NULL REFERENCES products (sku),
    quantity    INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 999),
    unit_price  NUMERIC(12, 2) NOT NULL,
    line_total  NUMERIC(12, 2) NOT NULL,
    CONSTRAINT order_lines_order_line_uk UNIQUE (order_id, line_no)
);
