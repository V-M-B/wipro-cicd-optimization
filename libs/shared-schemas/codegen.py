"""Generate Java, TypeScript and Python types from the shared JSON schemas.

Dependency-free on purpose so every pipeline stage can run it.

Usage:
    python libs/shared-schemas/codegen.py          # write generated files
    python libs/shared-schemas/codegen.py --check  # exit 1 if generated files are stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SCHEMAS = HERE / "schemas"
HEADER = "Generated by libs/shared-schemas/codegen.py. Do not edit."

JAVA_DIR = ROOT / "apps/orders-api/src/main/java/com/retailops/schemas"
TS_FILE = ROOT / "apps/web/src/generated/schemas.ts"
PY_DIR = ROOT / "apps/analytics/app/generated"


def load() -> tuple[dict[str, list[str]], list[dict]]:
    enums = json.loads((SCHEMAS / "enums.json").read_text(encoding="utf-8"))["enums"]
    models = [
        json.loads(p.read_text(encoding="utf-8"))
        for p in sorted(SCHEMAS.glob("*.schema.json"))
    ]
    return enums, models


def ref_name(ref: str) -> str:
    return ref.split("#")[-1]


# ---------------------------------------------------------------- Java
def java_type(prop: dict, required: bool) -> str:
    if "$ref" in prop:
        return ref_name(prop["$ref"])
    t = prop["type"]
    if t == "string":
        return "java.time.OffsetDateTime" if prop.get("format") == "date-time" else "String"
    if t == "number":
        return "java.math.BigDecimal"
    if t == "integer":
        return "int" if required else "Integer"
    if t == "boolean":
        return "boolean" if required else "Boolean"
    if t == "array":
        return f"java.util.List<{java_type(prop['items'], False)}>"
    raise ValueError(f"unsupported type {t}")


def gen_java(enums: dict, models: list[dict]) -> dict[Path, str]:
    out: dict[Path, str] = {}
    pkg = "package com.retailops.schemas;\n\n"
    for name, values in enums.items():
        body = ",\n    ".join(values)
        out[JAVA_DIR / f"{name}.java"] = (
            f"// {HEADER}\n{pkg}public enum {name} {{\n    {body}\n}}\n"
        )
    for m in models:
        req = set(m.get("required", []))
        fields = ",\n        ".join(
            f"{java_type(p, k in req)} {k}" for k, p in m["properties"].items()
        )
        out[JAVA_DIR / f"{m['title']}.java"] = (
            f"// {HEADER}\n{pkg}public record {m['title']}(\n        {fields}) {{\n}}\n"
        )
    return out


# ---------------------------------------------------------------- TypeScript
def ts_type(prop: dict) -> str:
    if "$ref" in prop:
        return ref_name(prop["$ref"])
    t = prop["type"]
    if t in ("number", "integer"):
        return "number"
    if t == "array":
        return f"{ts_type(prop['items'])}[]"
    return {"string": "string", "boolean": "boolean"}[t]


def gen_ts(enums: dict, models: list[dict]) -> dict[Path, str]:
    lines = [f"// {HEADER}", ""]
    for name, values in enums.items():
        lines.append(f"export const {name}Values = [{', '.join(repr(v) for v in values)}] as const;")
        lines.append(f"export type {name} = (typeof {name}Values)[number];")
        lines.append("")
    for m in models:
        req = set(m.get("required", []))
        lines.append(f"export interface {m['title']} {{")
        for k, p in m["properties"].items():
            opt = "" if k in req else "?"
            lines.append(f"  {k}{opt}: {ts_type(p)};")
        lines.append("}")
        lines.append("")
    return {TS_FILE: "\n".join(lines).replace("'", '"')}


# ---------------------------------------------------------------- Python
def py_type(prop: dict) -> str:
    if "$ref" in prop:
        return ref_name(prop["$ref"])
    t = prop["type"]
    if t == "string":
        return "datetime" if prop.get("format") == "date-time" else "str"
    if t == "array":
        return f"list[{py_type(prop['items'])}]"
    return {"number": "float", "integer": "int", "boolean": "bool"}[t]


def gen_py(enums: dict, models: list[dict]) -> dict[Path, str]:
    lines = [
        f'"""{HEADER}"""',
        "from __future__ import annotations",
        "",
        "from datetime import datetime",
        "from enum import Enum",
        "",
        "from pydantic import BaseModel",
        "",
    ]
    for name, values in enums.items():
        lines.append("")
        lines.append(f"class {name}(str, Enum):")
        lines.extend(f'    {v} = "{v}"' for v in values)
        lines.append("")
    # OrderLine must precede Order: emit models that others reference first
    ordered = sorted(models, key=lambda m: 0 if m["title"] == "OrderLine" else 1)
    for m in ordered:
        req = set(m.get("required", []))
        lines.append("")
        lines.append(f"class {m['title']}(BaseModel):")
        for k, p in m["properties"].items():
            t = py_type(p)
            lines.append(f"    {k}: {t}" if k in req else f"    {k}: {t} | None = None")
        lines.append("")
    return {
        PY_DIR / "schemas.py": "\n".join(lines),
        PY_DIR / "__init__.py": f'"""{HEADER}"""\n',
    }


def main(argv: list[str]) -> int:
    check = "--check" in argv
    enums, models = load()
    files: dict[Path, str] = {}
    for gen in (gen_java, gen_ts, gen_py):
        files.update(gen(enums, models))
    stale = []
    for path, content in sorted(files.items()):
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    if check and stale:
        print("Generated files are stale; run codegen.py:", *stale, sep="\n  ")
        return 1
    print(f"codegen: {len(files)} files, {len(stale)} {'stale' if check else 'written'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
