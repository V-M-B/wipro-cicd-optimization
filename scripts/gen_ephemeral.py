"""Generate .github/workflows/ci-ephemeral.yml from ci-optimized.yml (stage 4 = stage 3 on ARC runners).

Differences, and nothing else:
  - runs-on: arc-retailops (ephemeral, autoscaled self-hosted runners; one pod per job)
  - toolchain setup steps removed (JDK, Node, Python preinstalled in the warm runner image)
  - Playwright browser cache/install steps removed (browsers + system deps baked into the image)
  - every job is gated on the repository variable ARC_ENABLED == 'true', so pushes do not queue forever
    while the local cluster is down
  - triggers: exp/e/** pushes (replay round E) and manual dispatch only (never main)

Run: python scripts/gen_ephemeral.py   (CI does not run this; the generated file is committed)
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".github/workflows/ci-optimized.yml"
DST = ROOT / ".github/workflows/ci-ephemeral.yml"

STEP_BLOCK = r"      - (?:uses: actions/setup-(?:java|node|python)@v\d+|name: (?:Resolve Playwright version|Restore Playwright browser cache|Install Playwright browser|Install Playwright system dependencies))\n(?:        .*\n|\n(?=        ))*"


def main() -> int:
    t = SRC.read_text(encoding="utf-8")
    header_end = t.index("name: ci-optimized")
    t = (
        "# GENERATED by scripts/gen_ephemeral.py from ci-optimized.yml - do not edit by hand.\n"
        "# Stage 4 (Phase 5): stage 3 on ephemeral autoscaled ARC runners with a warm image. See ADR-0007.\n"
        + t[header_end:]
    )
    t = t.replace("name: ci-optimized", "name: ci-ephemeral", 1)
    t = t.replace('    branches: [main, "exp/a/**", "exp/e/**"]', '    branches: ["exp/e/**"]')
    t = t.replace("group: ci-optimized-", "group: ci-ephemeral-")
    t = t.replace("retailops-optimized", "retailops-ephemeral").replace("scope=optimized-", "scope=ephemeral-")
    t = t.replace("runs-on: ubuntu-latest", "runs-on: arc-retailops")
    t, n = re.subn(STEP_BLOCK, "", t)
    # gate the root job; every other job needs it
    t = t.replace("  select:\n    runs-on: arc-retailops",
                  "  select:\n    if: vars.ARC_ENABLED == 'true'\n    runs-on: arc-retailops")
    # e2e no longer needs the Playwright version output
    DST.write_text(t, encoding="utf-8", newline="\n")
    print(f"wrote {DST.relative_to(ROOT)} ({n} setup steps removed)")
    leftovers = re.findall(r"setup-(?:java|node|python)|ms-playwright|steps\.pw", t)
    if leftovers:
        raise SystemExit(f"unexpected leftovers: {leftovers}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
